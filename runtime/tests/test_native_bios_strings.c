/* Differential fixture for the native kernel's A0 string services. Each case
 * runs the generated OpenBIOS routine and psx_native_bios_service on the same
 * guest RAM and registers, then requires the same v0 and the same RAM. Built
 * and run by test_native_bios_strings.py, which extracts the reference bodies.
 * Device and scheduler boundaries are not reached by these services and fail
 * loudly if they are. */
#include "cpu_state.h"
#include "native_bios_services.h"
#include "psx_cycles.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

void reference_1FC058C8(CPUState *cpu);
void reference_1FC05A44(CPUState *cpu);
void reference_1FC05A68(CPUState *cpu);
void reference_1FC0590C(CPUState *cpu);
void reference_1FC05930(CPUState *cpu);
void reference_1FC059CC(CPUState *cpu);
void reference_1FC0596C(CPUState *cpu);
void reference_1FC05858(CPUState *cpu);
void reference_1FC05878(CPUState *cpu);
void reference_1FC060C4(CPUState *cpu);
void reference_1FC08674(CPUState *cpu);
void reference_1FC05894(CPUState *cpu);

enum { RAM_BYTES = 2u << 20, COMPARED = 0x20000, RETURN_PC = 0x80001230u,
       FIRST = 0x10000, SECOND = 0x11000, DEST = 0x12000 };

uint64_t psx_cycle_count, psx_next_service_cycle = UINT64_MAX;
int psx_in_device_service, g_event_step_conservative, g_ls_replay_active;
uint32_t g_psx_cyc_batch, g_psx_cyc_batch_limit;
uint32_t g_psx_gcs_recip_q16 = 65536u, g_psx_gcs_frac;
uint32_t g_psx_ram_size = RAM_BYTES, g_psx_ram_mask = RAM_BYTES - 1;
uint32_t g_debug_last_store_pc;
volatile uint32_t g_psx_last_fn_entry;
static uint8_t ram[RAM_BYTES];

static void unexpected(const char *boundary)
{
    fprintf(stderr, "string fixture reached %s\n", boundary);
    exit(1);
}

int cdrom_has_disc(void) { unexpected("cdrom_has_disc"); return 0; }
uint32_t dma_cycles_to_internal_event(void) { return UINT32_MAX; }
void psx_advance_cycles_slow(uint32_t cycles) { psx_cycle_count += cycles; }
void psx_devices_service_to_now(void) { unexpected("device service"); }
void psx_icache_reset(void) { unexpected("icache reset"); }
int psx_mod_read_disc_file(const char *path, void *buffer, uint32_t capacity, uint32_t *size)
{
    (void)path; (void)buffer; (void)capacity; (void)size;
    unexpected("disc read");
    return 0;
}
int psx_native_card_service(CPUState *cpu, uint32_t vector, uint32_t fn)
{
    (void)cpu; (void)vector; (void)fn;
    return 0;
}
uint32_t psx_sched_current_tcb(CPUState *cpu) { (void)cpu; unexpected("scheduler"); return 0; }
int psx_syscall(CPUState *cpu, uint32_t code) { (void)cpu; (void)code; unexpected("syscall"); return 0; }
void psx_check_interrupts_at(CPUState *cpu, uint32_t pc) { (void)cpu; (void)pc; }

static uint32_t read_word(uint32_t a) { uint32_t v; memcpy(&v, ram + (a & 0x1ffffcu), 4); return v; }
static void write_word(uint32_t a, uint32_t v) { memcpy(ram + (a & 0x1ffffcu), &v, 4); }
static uint8_t read_byte(uint32_t a) { return ram[a & 0x1fffffu]; }
static void write_byte(uint32_t a, uint8_t v) { ram[a & 0x1fffffu] = v; }
static uint16_t read_half(uint32_t a) { return (uint16_t)(read_byte(a) | read_byte(a + 1) << 8); }
static void write_half(uint32_t a, uint16_t v) { write_byte(a, (uint8_t)v); write_byte(a + 1, (uint8_t)(v >> 8)); }
uint8_t psx_cyc_load_byte(CPUState *cpu, uint32_t address, uint32_t rt, uint32_t mask)
{
    (void)rt; (void)mask;
    return cpu->read_byte(address);
}
/* The generated byte store falls back to the canonical store and counts its
 * bus width (headroom_counters.h); memory.c owns both in the runtime. */
uint64_t psx_hr_bus_callbacks[2][3];
void psx_write_byte(uint32_t address, uint8_t value) { write_byte(address, value); }

/* Signed bytes, empty strings, shared prefixes and path separators. */
static const char *const strings[] = {
    "", "a", "ab", "abc", "abd", "ba", "hello world", "\xe9t\xe9", "\x80", "\xff\x01",
    "a\xe9", "aab", "TEAM.DAT", "cdrom:\\FIFA\\DATA.BIN;1", "zz",
};
enum { STRING_COUNT = sizeof strings / sizeof strings[0] };
static const uint32_t counts[] = {0, 1, 2, 3, 5, 64, 0x7fffffffu, 0xffffffffu};
static const uint32_t searched[] = {0, 'a', 'b', 't', '\\', 0x80, 0xe9, 0xffffffe9u,
                                    0x161, 0xffffff80u, 'q'};
static uint8_t initial[COMPARED], result_ram[2][COMPARED];
static unsigned cases;

static void place(uint32_t first, uint32_t second)
{
    memset(initial, 0xa5, sizeof initial);
    memcpy(initial + FIRST, strings[first], strlen(strings[first]) + 1);
    memcpy(initial + SECOND, strings[second], strlen(strings[second]) + 1);
    memcpy(initial + DEST, strings[second], strlen(strings[second]) + 1);
}

static void compare(const char *name, uint32_t fn, void (*reference)(CPUState *),
                    uint32_t a0, uint32_t a1, uint32_t a2)
{
    uint32_t v0[2];
    for (int native = 0; native < 2; ++native) {
        CPUState cpu = {0};
        memcpy(ram, initial, sizeof initial);
        cpu.read_word = read_word; cpu.write_word = write_word;
        cpu.read_half = read_half; cpu.write_half = write_half;
        cpu.read_byte = read_byte; cpu.write_byte = write_byte;
        cpu.gpr[2] = 0xdeadbeefu;
        cpu.gpr[4] = a0; cpu.gpr[5] = a1; cpu.gpr[6] = a2;
        cpu.gpr[9] = fn;
        cpu.gpr[31] = RETURN_PC;
        if (native) {
            if (psx_native_bios_service(&cpu, 0xa0, fn) != PSX_NATIVE_BIOS_RETURN) {
                fprintf(stderr, "A0:%02X %s is not a native service\n", fn, name);
                exit(1);
            }
        } else {
            reference(&cpu);
            if (cpu.pc == 0xBFC08674u) {  /* bcmp/memcmp tail jump */
                cpu.pc = 0;
                reference_1FC08674(&cpu);
            }
            if (cpu.pc != RETURN_PC) {
                fprintf(stderr, "reference %s did not return\n", name);
                exit(1);
            }
        }
        v0[native] = cpu.gpr[2];
        memcpy(result_ram[native], ram, sizeof initial);
    }
    ++cases;
    if (v0[0] != v0[1] || memcmp(result_ram[0], result_ram[1], sizeof initial)) {
        fprintf(stderr, "A0:%02X %s(%08x, %08x, %08x): OpenBIOS v0=%08x, native v0=%08x%s\n",
                fn, name, a0, a1, a2, v0[0], v0[1],
                memcmp(result_ram[0], result_ram[1], sizeof initial) ? ", RAM differs" : "");
        exit(1);
    }
}

int main(void)
{
    for (uint32_t i = 0; i < STRING_COUNT; ++i) {
        for (uint32_t j = 0; j < STRING_COUNT; ++j) {
            place(i, j);
            compare("strcmp", 0x17, reference_1FC05A44, FIRST, SECOND, 0);
            for (size_t k = 0; k < sizeof counts / sizeof counts[0]; ++k)
                compare("strncmp", 0x18, reference_1FC05A68, FIRST, SECOND, counts[k]);
            compare("strcat", 0x15, reference_1FC058C8, DEST, FIRST, 0);
            compare("strcpy", 0x19, reference_1FC0590C, DEST, FIRST, 0);
            for (size_t k = 0; k < 6; ++k)
                compare("strncpy", 0x1a, reference_1FC05930, DEST, FIRST, counts[k]);
            for (size_t k = 0; k < 6; ++k) {  /* bounded: equal buffers compare the whole count */
                compare("bcmp", 0x29, reference_1FC060C4, FIRST, SECOND, counts[k]);
                compare("memcmp", 0x2d, reference_1FC060C4, FIRST, SECOND, counts[k]);
            }
        }
        compare("memcmp", 0x2d, reference_1FC060C4, 0, SECOND, 4);
        compare("memcmp", 0x2d, reference_1FC060C4, FIRST, 0, 4);
        compare("strlen", 0x1b, reference_1FC059CC, FIRST, 0, 0);
        for (size_t k = 0; k < sizeof searched / sizeof searched[0]; ++k) {
            compare("index", 0x1c, reference_1FC0596C, FIRST, searched[k], 0);
            compare("strchr", 0x1e, reference_1FC0596C, FIRST, searched[k], 0);
            compare("memchr", 0x2e, reference_1FC05894, FIRST, searched[k], 16);
        }
    }
    place(0, 0);
    for (uint32_t value = 0; value < 0x200; ++value) {
        compare("toupper", 0x25, reference_1FC05858, value, 0, 0);
        compare("tolower", 0x26, reference_1FC05878, value, 0, 0);
    }
    const uint32_t wide[] = {0x80000041u, 0x80000061u, 0xffffff41u, 0xffffff61u,
                             0xffffffc1u, 0xffffffe1u, 0x141u, 0x161u, 0x7fffffffu};
    for (size_t k = 0; k < sizeof wide / sizeof wide[0]; ++k) {
        compare("toupper", 0x25, reference_1FC05858, wide[k], 0, 0);
        compare("tolower", 0x26, reference_1FC05878, wide[k], 0, 0);
    }
    printf("native A0 string services match OpenBIOS in %u cases\n", cases);
    return 0;
}
