static void power_on(void) {
    /* Power-on GPUREAD is 0 [G1b]; GP1(10h) 08h latches 0 through the
     * register path. */
    vram_read_active = 0;
    gp1_get_info(0x10000008u);
    /* G1b draw state: E2 E20ABCDE, E3 (123h,45h), E4 (2FFh,1DFh), E5 (7Ah,3F9h) */
    texture_window_value = 0x0ABCDEu;
    draw_area_left = 0x123u; draw_area_top = 0x45u;
    draw_area_right = 0x2FFu; draw_area_bottom = 0x1DFu;
    draw_offset_x = 0x7A; draw_offset_y = -7; /* 11-bit 3F9h */
}

static void c0(uint32_t x, uint32_t y, uint32_t w, uint32_t h) {
    gp0_cmd_buf[0] = 0xC0000000u;
    gp0_cmd_buf[1] = x | y << 16;
    gp0_cmd_buf[2] = w | h << 16;
    gp0_exec_vram_to_cpu();
}

static int failures;
#define CHECK(cond, ...) do { if (!(cond)) { failures++; \
    fprintf(stderr, "FAIL line %d: ", __LINE__); \
    fprintf(stderr, __VA_ARGS__); fputc('\n', stderr); } } while (0)

static void run_g1(void) {
    vram_pattern = g1_pattern;
    for (size_t i = 0; i < sizeof g1_cases / sizeof g1_cases[0]; ++i) {
        const G1Case *k = &g1_cases[i];
        power_on();
        c0((uint32_t)k->x, 0, (uint32_t)k->w, (uint32_t)k->h);
        for (int r = 0; r < k->n; ++r) {
            const G1Word *e = &k->words[r];
            CHECK(vram_read_active == e->bit27_before, "G1 x%d w%d h%d read %d bit27 before", k->x, k->w, k->h, r);
            uint32_t got = gpu_read_gpuread();
            CHECK(got == e->word, "G1 x%d w%d h%d read %d: %08X != %08X", k->x, k->w, k->h, r, got, e->word);
            CHECK(vram_read_active == e->bit27_after, "G1 x%d w%d h%d read %d bit27 after", k->x, k->w, k->h, r);
        }
    }
}

static void run_g1b(void) {
    vram_pattern = g1b_pattern;
    for (size_t i = 0; i < sizeof g1b_cases / sizeof g1b_cases[0]; ++i) {
        const G1bCase *k = &g1b_cases[i];
        power_on();
        g1b_hi = k->hi;
        draw_offset_y = (k->e5_y & 0x400u) ? (int)k->e5_y - 0x800 : (int)k->e5_y;
        for (int s = 0; s < k->n; ++s) {
            const G1bStep *t = &k->steps[s];
            if (t->op == 'G') gp1_get_info(0x10000000u | t->a);
            else if (t->op == 'C') c0(t->a, (uint32_t)t->b, (uint32_t)t->c, (uint32_t)t->d);
            else {
                uint32_t got = gpu_read_gpuread();
                CHECK(got == t->a, "%s step %d: %08X != %08X", k->name, s, got, t->a);
                CHECK(vram_read_active == t->b, "%s step %d bit27", k->name, s);
            }
        }
    }
}

/* Rules the fixture rows do not reach, by the rule labelled in gpu.c. */
static void run_rules(void) {
    vram_pattern = g1b_pattern;
    g1b_hi = 0x4444u;
    power_on();
    c0(0, 0, 3, 1);
    (void)gpu_read_gpuread(); (void)gpu_read_gpuread();
    /* 0Ah-0Eh leave the latch unchanged, as 09h and 0Fh do [G1c]. */
    gp1_get_info(0x10000003u);
    CHECK(gpu_read_gpuread() == 0x44411523u, "03 after C0h");
    for (uint32_t idx = 9; idx <= 0xF; ++idx) {
        gp1_get_info(0x10000000u | idx);
        CHECK(gpu_read_gpuread() == 0x44411523u, "index %02X unchanged", idx);
    }
    /* Index mod 10h through the GP1 command range 10h-1Fh. */
    gp1_get_info(0x10000012u);
    CHECK(gpu_read_gpuread() == 0x444ABCDEu, "index 12h mirrors 02h");
    gp1_get_info(0x10000017u);
    CHECK(gpu_read_gpuread() == 2u, "index 17h mirrors 07h");
    gp1_get_info(0x10000018u);
    CHECK(gpu_read_gpuread() == 0u, "index 18h mirrors 08h");
}

int main(void) {
    run_g1();
    run_g1b();
    run_rules();
    if (failures) {
        fprintf(stderr, "%d failure(s)\n", failures);
        return 1;
    }
    puts("PASS: GPUREAD after C0h and the GP1(10h) latch match G1, G1b and G1c");
    return 0;
}
