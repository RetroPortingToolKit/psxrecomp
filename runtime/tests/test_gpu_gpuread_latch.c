/* VRAM stub. Default pattern: halfword (x, y) = 4000h | y<<10 | x [G1]. */
static uint16_t (*vram_pattern)(int x, int y);
static uint16_t g1_pattern(int x, int y) { return (uint16_t)(0x4000u | (unsigned)y << 10 | (unsigned)x); }
static uint16_t g1b_hi = 0x4444u;
static uint16_t g1b_pattern(int x, int y) {
    /* (0,0)-(3,1) = 1111 2222 3333 4444 / 5555 6666 7777 8888 [G1b];
     * G1c replaces (3,0) with 00F0h or FFF0h. */
    if (x == 3 && y == 0) return g1b_hi;
    return (x < 4 && y < 2) ? (uint16_t)(0x1111u * (unsigned)(y * 4 + x + 1)) : 0;
}
uint16_t gr_vram_read(int x, int y) { return vram_pattern(x, y); }

