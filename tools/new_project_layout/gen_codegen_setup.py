#!/usr/bin/env python3
"""Generate codegen_setup.c/h for a PSXRecomp game from game.toml.

The framework scaffold fills these files from a template and a handful of
values that already live in game.toml. This generator removes the manual copy
step and provides --check for drift detection.

Usage, from a game repository root with psxrecomp/ checked out:
  python3 psxrecomp/tools/new_project_layout/gen_codegen_setup.py .
  python3 psxrecomp/tools/new_project_layout/gen_codegen_setup.py --check .

The environment prefix is preserved from an existing codegen_setup.c so titles
created with an older scaffold keep their variable names.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys
import tomllib

C_TEMPLATE = """/* Title config for psxrecomp/host/psxrecomp_codegen_host.
 * Wired only when the build opts into -DPSX_SETUP_WIZARD=ON.
 * Generated by psxrecomp/tools/new_project_layout/gen_codegen_setup.py from game.toml. */

#include "codegen_setup.h"

#include "psxrecomp_codegen_host.h"

static const PsxrecompCodegenHostConfig kCodegenConfig = {
    .display_name = "@GAME_NAME@",
    .project_root_env = "@ENV_PREFIX@_PROJECT_ROOT",
    .build_dir_env = "@ENV_PREFIX@_BUILD_DIR",
    .force_setup_env = "@ENV_PREFIX@_FORCE_SETUP",
    .psxrecomp_cli_relpath = "psxrecomp/psxrecomp_cli.py",
    .seed_cfg_relpath = "game.toml",
    .game_toml_relpath = "game.toml",
    .gen_marker_relpath = "generated/@BOOT_EXE@_dispatch.c",
    .build_dir_name = "build-release",
    .cmake_target = "psx-runtime",
    .exe_basename = "@EXE_BASENAME@",
    .prepare_note =
        "Uses your legal disc with the local psxrecomp SDK to generate "
        "BIOS + game C, then cmake --build. The product lives under "
        "build-release/; reopening this setup exe forwards there.",
    .prepare_note_windows =
        "Uses your legal disc with the local psxrecomp SDK to generate "
        "BIOS + game C, then quits and rebuilds via a helper. Afterward, "
        "this setup exe forwards to build-release/ (bios, mods, settings).",
    .prepare_note_no_cmake =
        "Uses your legal disc with the local psxrecomp SDK to generate "
        "BIOS + game C. Rebuild into build-release/, then relaunch this "
        "setup exe (it forwards to the product build).",
};

void psx_game_codegen_setup_apply(RecompLauncherCGameInfo* gi) {
    psxrecomp_codegen_host_apply(gi, &kCodegenConfig);
}

void psx_game_codegen_relaunch_or_exit(const char* disc_path) {
    psxrecomp_codegen_host_relaunch_or_exit(disc_path);
}

void psx_game_codegen_forward_if_built(int argc, char** argv) {
    psxrecomp_codegen_host_forward_if_built(&kCodegenConfig, argc, argv);
}
"""

H_TEMPLATE = """#ifndef CODEGEN_SETUP_H
#define CODEGEN_SETUP_H

#include "recomp_launcher.h"

#ifdef __cplusplus
extern "C" {
#endif

void psx_game_codegen_setup_apply(RecompLauncherCGameInfo* gi);
void psx_game_codegen_relaunch_or_exit(const char* disc_path);
void psx_game_codegen_forward_if_built(int argc, char** argv);

#ifdef __cplusplus
}
#endif

#endif
"""


def derive(root: pathlib.Path) -> dict[str, str]:
    with open(root / "game.toml", "rb") as handle:
        game = tomllib.load(handle)["game"]

    name = str(game["name"])
    boot_exe = pathlib.Path(str(game["exe"])).name

    existing = root / "codegen_setup.c"
    prefix = None
    if existing.is_file():
        match = re.search(
            r'\.project_root_env = "([A-Z0-9_]+)_PROJECT_ROOT"',
            existing.read_text(encoding="utf-8"),
        )
        if match:
            prefix = match.group(1)
    if prefix is None:
        prefix = re.sub(r"[^A-Z0-9]", "", name.upper()) + "RECOMP"

    return {
        "@GAME_NAME@": name,
        "@ENV_PREFIX@": prefix,
        "@BOOT_EXE@": boot_exe,
        "@EXE_BASENAME@": name + "_Recompiled",
    }


def render(template: str, values: dict[str, str]) -> str:
    text = template
    for key, value in values.items():
        text = text.replace(key, value)
    return text


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("project_root", nargs="?", default=".", type=pathlib.Path)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the files would change; write nothing",
    )
    args = parser.parse_args(argv)

    root = args.project_root.resolve()
    if not (root / "game.toml").is_file():
        print(f"error: missing {root / 'game.toml'}", file=sys.stderr)
        return 1

    values = derive(root)
    outputs = {
        root / "codegen_setup.c": render(C_TEMPLATE, values),
        root / "codegen_setup.h": render(H_TEMPLATE, values),
    }

    changed = []
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != text:
            changed.append(path.name)
            if not args.check:
                path.write_text(text, encoding="utf-8")

    if args.check:
        if changed:
            print(
                f"{root.name}: out of date: {', '.join(sorted(changed))}",
                file=sys.stderr,
            )
            return 1
        print(f"{root.name}: codegen_setup is current")
        return 0

    if changed:
        print(f"{root.name}: wrote {', '.join(sorted(changed))}")
    else:
        print(f"{root.name}: already current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
